-- Вариант 6. Учебный график дисциплин факультета.
-- PostgreSQL. Модель в третьей нормальной форме.
-- Создает таблицы, первичные и внешние ключи. Выполнять в пустой БД.
BEGIN;
CREATE SCHEMA faculty_3nf;

-- Факультеты университета.
CREATE TABLE faculty_3nf.faculty (
    faculty_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    faculty_code VARCHAR(20) NOT NULL UNIQUE,
    faculty_name VARCHAR(200) NOT NULL
);
COMMENT ON TABLE faculty_3nf.faculty IS 'Факультеты университета';

-- Образовательные программы факультета.
CREATE TABLE faculty_3nf.study_program (
    program_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    faculty_id BIGINT NOT NULL,
    program_code VARCHAR(30) NOT NULL UNIQUE,
    program_name VARCHAR(200) NOT NULL,
    degree_level VARCHAR(30) NOT NULL,
    CONSTRAINT fk_study_program_faculty_id FOREIGN KEY (faculty_id) REFERENCES faculty_3nf.faculty (faculty_id)
);
COMMENT ON TABLE faculty_3nf.study_program IS 'Образовательные программы факультета';

-- Учебные группы.
CREATE TABLE faculty_3nf.study_group (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    program_id BIGINT NOT NULL,
    group_code VARCHAR(30) NOT NULL UNIQUE,
    admission_year SMALLINT NOT NULL,
    CONSTRAINT fk_study_group_program_id FOREIGN KEY (program_id) REFERENCES faculty_3nf.study_program (program_id)
);
COMMENT ON TABLE faculty_3nf.study_group IS 'Учебные группы';

-- Дисциплины.
CREATE TABLE faculty_3nf.discipline (
    discipline_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    discipline_code VARCHAR(30) NOT NULL UNIQUE,
    discipline_name VARCHAR(200) NOT NULL
);
COMMENT ON TABLE faculty_3nf.discipline IS 'Дисциплины';

-- Преподаватели.
CREATE TABLE faculty_3nf.teacher (
    teacher_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    faculty_id BIGINT NOT NULL,
    personnel_no VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(200) NOT NULL,
    position_name VARCHAR(100) NOT NULL,
    CONSTRAINT fk_teacher_faculty_id FOREIGN KEY (faculty_id) REFERENCES faculty_3nf.faculty (faculty_id)
);
COMMENT ON TABLE faculty_3nf.teacher IS 'Преподаватели';

-- Учебные периоды.
CREATE TABLE faculty_3nf.academic_term (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    term_code VARCHAR(20) NOT NULL UNIQUE,
    academic_year_start SMALLINT NOT NULL,
    term_no SMALLINT NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    UNIQUE (academic_year_start, term_no),
    CHECK (starts_on <= ends_on)
);
COMMENT ON TABLE faculty_3nf.academic_term IS 'Учебные периоды';

-- Дисциплины учебного плана по семестрам.
CREATE TABLE faculty_3nf.curriculum_item (
    curriculum_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    program_id BIGINT NOT NULL,
    discipline_id BIGINT NOT NULL,
    semester_no SMALLINT NOT NULL,
    lecture_hours SMALLINT NOT NULL,
    practice_hours SMALLINT NOT NULL,
    lab_hours SMALLINT NOT NULL,
    assessment_type VARCHAR(30) NOT NULL,
    UNIQUE (program_id, discipline_id, semester_no),
    CONSTRAINT fk_curriculum_item_program_id FOREIGN KEY (program_id) REFERENCES faculty_3nf.study_program (program_id),
    CONSTRAINT fk_curriculum_item_discipline_id FOREIGN KEY (discipline_id) REFERENCES faculty_3nf.discipline (discipline_id),
    CHECK (lecture_hours >= 0 AND practice_hours >= 0 AND lab_hours >= 0),
    CHECK (semester_no BETWEEN 1 AND 12)
);
COMMENT ON TABLE faculty_3nf.curriculum_item IS 'Дисциплины учебного плана по семестрам';

-- Занятия в учебном графике.
CREATE TABLE faculty_3nf.class_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    group_id BIGINT NOT NULL,
    curriculum_item_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room_code VARCHAR(30) NOT NULL,
    lesson_type VARCHAR(30) NOT NULL,
    CONSTRAINT fk_class_session_group_id FOREIGN KEY (group_id) REFERENCES faculty_3nf.study_group (group_id),
    CONSTRAINT fk_class_session_curriculum_item_id FOREIGN KEY (curriculum_item_id) REFERENCES faculty_3nf.curriculum_item (curriculum_item_id),
    CONSTRAINT fk_class_session_teacher_id FOREIGN KEY (teacher_id) REFERENCES faculty_3nf.teacher (teacher_id),
    CONSTRAINT fk_class_session_term_id FOREIGN KEY (term_id) REFERENCES faculty_3nf.academic_term (term_id),
    CHECK (start_time < end_time)
);
COMMENT ON TABLE faculty_3nf.class_session IS 'Занятия в учебном графике';

COMMIT;
